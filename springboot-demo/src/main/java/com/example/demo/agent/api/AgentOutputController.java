package com.example.demo.agent.api;

import com.example.demo.agent.dto.AgentFileView;
import com.example.demo.agent.service.AgentOutputService;
import com.example.demo.agent.service.attachment.AttachmentStorage;
import com.example.demo.agent.workbook.AgentWorkbookService;
import com.example.demo.agent.workbook.AgentWorkbookSpec;
import com.example.demo.common.ApiResponse;
import com.example.demo.config.AuthInterceptor;
import com.example.demo.excel.entity.ExcelTaskOutput;
import com.example.demo.security.AuthSession;
import jakarta.servlet.http.HttpServletRequest;
import org.springframework.http.ContentDisposition;
import org.springframework.http.HttpHeaders;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;
import org.springframework.web.servlet.mvc.method.annotation.StreamingResponseBody;
import org.springframework.util.StringUtils;

import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.Map;

/** Files generated by the agent for the signed-in user: list, download and delete. */
@RestController
@RequestMapping("/agent")
public class AgentOutputController {
    private final AgentOutputService service;
    private final AttachmentStorage storage;
    private final AgentWorkbookService workbookService;

    public AgentOutputController(AgentOutputService service, AttachmentStorage storage,
                                 AgentWorkbookService workbookService) {
        this.service = service;
        this.storage = storage;
        this.workbookService = workbookService;
    }

    @GetMapping("/outputs")
    public ApiResponse<List<AgentFileView>> list(HttpServletRequest request) {
        return ApiResponse.ok(service.listMine(currentUserId(request)));
    }

    @GetMapping("/runs/{runId}/outputs")
    public ApiResponse<List<AgentFileView>> forRun(@PathVariable Long runId, HttpServletRequest request) {
        return ApiResponse.ok(service.forRun(runId, currentUserId(request)));
    }

    @GetMapping("/outputs/{outputId}")
    public ApiResponse<AgentFileView> get(@PathVariable Long outputId, HttpServletRequest request) {
        return ApiResponse.ok(service.get(outputId, currentUserId(request)));
    }

    @GetMapping("/outputs/{outputId}/workbook")
    public ApiResponse<Map<String, Object>> workbook(@PathVariable Long outputId, HttpServletRequest request) {
        return ApiResponse.ok(service.readWorkbookContent(outputId, currentUserId(request), null, 200));
    }

    @PostMapping("/outputs/{outputId}/workbook-versions")
    public ApiResponse<Map<String, Object>> saveWorkbookVersion(@PathVariable Long outputId,
                                                                 @RequestBody AgentWorkbookSpec spec,
                                                                 HttpServletRequest request) {
        Long operatorId = currentUserId(request);
        AgentFileView source = service.get(outputId, operatorId);
        service.readWorkbookContent(outputId, operatorId, null, 1);
        if (!StringUtils.hasText(spec.getTitle())) {
            String name = StringUtils.hasText(source.name()) ? source.name().replaceFirst("(?i)\\.xlsx$", "") : "表格";
            spec.setTitle(name + "-修改版");
        }
        spec.setAttachmentId(null);
        spec.setIncludeSourceText(false);
        spec.setNote("基于文件 #" + outputId + " 快速修改生成；原文件保留。");
        return ApiResponse.ok("新版本已生成", workbookService.generate(null, operatorId, spec));
    }

    @GetMapping("/outputs/{outputId}/download")
    public ResponseEntity<StreamingResponseBody> download(@PathVariable Long outputId, HttpServletRequest request) {
        ExcelTaskOutput output = service.openForDownload(outputId, currentUserId(request));
        StreamingResponseBody body = stream -> {
            try (var input = storage.openStream(output.getObjectKey())) {
                input.transferTo(stream);
            }
        };
        return ResponseEntity.ok()
                .header(HttpHeaders.CONTENT_DISPOSITION, ContentDisposition.attachment()
                        .filename(output.getOriginalName(), StandardCharsets.UTF_8).build().toString())
                .header(HttpHeaders.CONTENT_TYPE, output.getMimeType())
                .contentLength(output.getFileSize())
                .body(body);
    }

    @DeleteMapping("/outputs/{outputId}")
    public ApiResponse<Void> delete(@PathVariable Long outputId, HttpServletRequest request) {
        return deleteOutput(outputId, request);
    }

    /** Compatibility endpoint for gateways that do not reliably forward DELETE. */
    @PostMapping("/outputs/{outputId}/delete")
    public ApiResponse<Void> deleteByPost(@PathVariable Long outputId, HttpServletRequest request) {
        return deleteOutput(outputId, request);
    }

    private ApiResponse<Void> deleteOutput(Long outputId, HttpServletRequest request) {
        service.delete(outputId, currentUserId(request));
        return ApiResponse.ok("文件已删除", null);
    }

    private Long currentUserId(HttpServletRequest request) {
        Object value = request.getAttribute(AuthInterceptor.AUTH_SESSION_ATTRIBUTE);
        if (!(value instanceof AuthSession session) || session.getUser() == null) {
            throw new IllegalArgumentException("无法识别当前操作人");
        }
        return session.getUser().getId();
    }
}
